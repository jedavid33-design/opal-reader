// Opal Reader v2 — derive the coordinator's pinned chunk manifest
// for the chunked migration import (D3; cutover plan §S3 as
// corrected, Rowan D1 sign-off 6355565715).
//
// Usage: node tools/derive-approved-freeze-chunks.mjs [--check]
//
// Reads the COMMITTED approved-freeze manifest
// (v2/p8/approved-freeze-manifest.mjs — itself derived from Julie's
// approved frozen snapshot by tools/derive-approved-freeze-
// manifest.mjs and cross-checked against the binding audit) and
// emits v2/p8/approved-freeze-chunks.mjs: per book, the exact
// ordered chunk partition of the pinned row set under the code
// limits (v2/p8/migration-chunk-limits.mjs). Each chunk records
// only its slice coordinates into the pinned rows (start +
// rowCount), its byte total, and a row-set digest over the slice's
// pinned tuples — digests/metadata only, no book text, no audio.
//
// A chunk's rows are a CONTIGUOUS SLICE of the book's pinned rows
// (partitionBookRows fills greedily in pinned order), so membership
// and order are provable from the whole-book pin alone: the
// coordinator re-derives the slice from the book pin and verifies
// this module's per-chunk digest over it before any chunk command
// is primed. Caller input may only MATCH this data, never define
// it — the same G2 discipline as the whole-book pin.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { APPROVED_FREEZE_MANIFEST } from "../v2/p8/approved-freeze-manifest.mjs";
import { MIGRATION_CHUNK_LIMITS, partitionBookRows } from "../v2/p8/migration-chunk-limits.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "v2", "p8", "approved-freeze-chunks.mjs");
const checkOnly = process.argv.includes("--check");

// Canonical JSON (sorted keys, recursively) — the same discipline
// as v2/coordinator.mjs's canonicalJson; digests must agree.
function canonicalJson(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  return `{${Object.keys(value).sort()
    .map(k => `${JSON.stringify(k)}:${canonicalJson(value[k])}`).join(",")}}`;
}
const sha256HexText = (text) => createHash("sha256").update(text, "utf8").digest("hex");
const fail = (msg) => { console.error(`derive-approved-freeze-chunks: ${msg}`); process.exit(1); };

const books = {};
let totalChunks = 0, totalRows = 0;
for (const bookId of Object.keys(APPROVED_FREEZE_MANIFEST.books).sort()) {
  const book = APPROVED_FREEZE_MANIFEST.books[bookId];
  // Normalized rows for the partitioner (size is the field it reads).
  const rows = book.rows.map(t => ({ size: t[3] }));
  let parts;
  try { parts = partitionBookRows(rows, MIGRATION_CHUNK_LIMITS); }
  catch (e) { fail(`${bookId}: ${e.message}`); }
  const chunks = parts.map(c => ({
    ...c,
    // The per-chunk row-set digest: over the slice's pinned tuples
    // exactly as the whole-book pin stores them (field order:
    // occurrenceId, revisionKey, cacheKey, size, format,
    // sha256Prefix, etag).
    rowsSha256: sha256HexText(canonicalJson(
      book.rows.slice(c.start, c.start + c.rowCount))),
  }));
  const totalBytes = chunks.reduce((n, c) => n + c.totalBytes, 0);
  const pinnedBytes = book.rows.reduce((n, t) => n + t[3], 0);
  if (totalBytes !== pinnedBytes)
    fail(`${bookId}: chunk byte total ${totalBytes} != pinned byte total ${pinnedBytes}`);
  books[bookId] = { chunkCount: chunks.length, totalBytes, chunks };
  totalChunks += chunks.length; totalRows += book.rows.length;
}
if (totalRows !== 1799) fail(`row count ${totalRows} != 1799`);

const lines = [];
lines.push("// Opal Reader v2 — the APPROVED FREEZE CHUNK PIN (D3).");
lines.push("//");
lines.push("// The chunked migration import's authoritative partition of");
lines.push("// the approved freeze: per book, the exact ordered chunks of");
lines.push("// the pinned row set under the code limits in");
lines.push("// v2/p8/migration-chunk-limits.mjs. A chunk's rows are the");
lines.push("// contiguous slice [start, start + rowCount) of the book's");
lines.push("// pinned rows in v2/p8/approved-freeze-manifest.mjs;");
lines.push("// rowsSha256 is the canonical digest over that slice's pinned");
lines.push("// tuples, so the coordinator can verify this pin against the");
lines.push("// whole-book pin before priming anything. Generated by");
lines.push("// tools/derive-approved-freeze-chunks.mjs from the committed");
lines.push("// approved-freeze manifest — digests/metadata only (slice");
lines.push("// coordinates, byte totals, digests); no book text, no audio");
lines.push("// bytes. Do not hand-edit: regenerate.");
lines.push("");
lines.push(`export const APPROVED_FREEZE_CHUNKS = Object.freeze({`);
lines.push(`  snapshotDigest: ${JSON.stringify(APPROVED_FREEZE_MANIFEST.snapshotDigest)},`);
lines.push(`  limits: Object.freeze({ maxRowsPerChunk: ${MIGRATION_CHUNK_LIMITS.maxRowsPerChunk}, maxChunkBytes: ${MIGRATION_CHUNK_LIMITS.maxChunkBytes}, maxItemBytes: ${MIGRATION_CHUNK_LIMITS.maxItemBytes} }),`);
lines.push("  books: Object.freeze({");
for (const bookId of Object.keys(books).sort()) {
  const b = books[bookId];
  lines.push(`    ${JSON.stringify(bookId)}: Object.freeze({ chunkCount: ${b.chunkCount}, totalBytes: ${b.totalBytes}, chunks: Object.freeze([`);
  for (const c of b.chunks)
    lines.push(`      Object.freeze({ index: ${c.index}, start: ${c.start}, rowCount: ${c.rowCount}, totalBytes: ${c.totalBytes}, rowsSha256: ${JSON.stringify(c.rowsSha256)} }),`);
  lines.push("    ]) }),");
}
lines.push("  }),");
lines.push("});");
lines.push("");
const text = lines.join("\n");

if (checkOnly) {
  const current = readFileSync(OUT, "utf8");
  if (current !== text) fail("committed chunk pin differs from the derived chunk pin (--check)");
  console.log("approved freeze chunk pin: up to date");
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
console.log(`books: ${Object.keys(books).length}, rows: ${totalRows}, chunks: ${totalChunks}, limits: ${JSON.stringify(MIGRATION_CHUNK_LIMITS)}`);
for (const bookId of Object.keys(books).sort())
  console.log(`  ${bookId}: ${books[bookId].chunkCount} chunks (${books[bookId].chunks.map(c => `${c.rowCount} rows/${c.totalBytes} B`).join(", ")})`);
